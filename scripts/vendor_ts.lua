-- Vendor tree-sitter grammar sources + queries into this config.
-- Needs network; run on a connected machine, then commit the result.
--
--   git clone --depth 1 https://github.com/nvim-treesitter/nvim-treesitter /tmp/nts
--   nvim -l scripts/vendor_ts.lua /tmp/nts
--
-- Grammar revisions and queries are taken from that nvim-treesitter checkout,
-- so parser and queries always match. Only MIT-licensed grammars are listed.
-- Output: ts/grammars/<lang>/{src,LICENSE}, queries/<lang>/*.scm, THIRD_PARTY.md

local nts = arg[1]
assert(nts, 'usage: nvim -l scripts/vendor_ts.lua <nvim-treesitter checkout>')

local root = vim.fn.fnamemodify(arg[0], ':p:h:h')

local LANGS = {
  -- required
  'python', 'json', 'html', 'css', 'java', 'sql', 'markdown', 'markdown_inline', 'diff', 'c', 'cpp',
  -- extras
  'lua', 'vim', 'bash', 'javascript', 'typescript', 'tsx', 'go', 'rust', 'yaml', 'toml',
  'dockerfile', 'make', 'cmake', 'regex', 'gitcommit', 'git_config',
}
-- queries-only languages that others `; inherits:` from
local QUERY_ONLY = { 'ecma', 'jsx', 'html_tags' }

local parsers = dofile(nts .. '/lua/nvim-treesitter/parsers.lua')

local function run(cmd, cwd)
  local r = vim.system(cmd, { cwd = cwd, text = true }):wait()
  if r.code ~= 0 then error(table.concat(cmd, ' ') .. '\n' .. (r.stderr or '')) end
  return r.stdout
end

local function copy_queries(lang)
  local src = nts .. '/runtime/queries/' .. lang
  local dst = root .. '/queries/' .. lang
  vim.fn.delete(dst, 'rf')
  vim.fn.mkdir(dst, 'p')
  run({ 'sh', '-c', ('cp %s/*.scm %s/'):format(vim.fn.shellescape(src), vim.fn.shellescape(dst)) })
end

local cloned = {} -- "url@rev" -> checkout dir
local tmp = vim.fn.tempname()
vim.fn.mkdir(tmp, 'p')

local manifest = {}

for _, lang in ipairs(LANGS) do
  local info = parsers[lang].install_info
  assert(not info.generate, lang .. ' needs `tree-sitter generate`; not supported')
  local key = info.url .. '@' .. info.revision
  if not cloned[key] then
    local dir = tmp .. '/' .. #vim.tbl_keys(cloned)
    vim.fn.mkdir(dir, 'p')
    run({ 'git', 'init', '-q' }, dir)
    run({ 'git', 'fetch', '-q', '--depth', '1', info.url, info.revision }, dir)
    run({ 'git', 'checkout', '-q', 'FETCH_HEAD' }, dir)
    cloned[key] = dir
  end
  local repo = cloned[key]
  local loc = info.location and (repo .. '/' .. info.location) or repo

  local dst = root .. '/ts/grammars/' .. lang
  vim.fn.delete(dst, 'rf')
  vim.fn.mkdir(dst, 'p')
  -- sources: src/ only (parser.c, scanner.*, tree_sitter/*.h)
  run({ 'sh', '-c', ('cp -r %s/src %s/src'):format(vim.fn.shellescape(loc), vim.fn.shellescape(dst)) })
  run({ 'sh', '-c', ('rm -rf %s/src/grammar.json %s/src/node-types.json'):format(vim.fn.shellescape(dst), vim.fn.shellescape(dst)) })
  -- shared headers some scanners include as ../../common/ (typescript, tsx)
  if vim.uv.fs_stat(repo .. '/common') then
    local cdst = root .. '/ts/grammars/common'
    vim.fn.delete(cdst, 'rf')
    run({ 'cp', '-r', repo .. '/common', cdst })
  end
  -- licence: next to the grammar, else repo root
  local lic
  for _, d in ipairs({ loc, repo }) do
    for _, n in ipairs({ 'LICENSE', 'LICENSE.md', 'LICENSE.txt', 'COPYING' }) do
      if not lic and vim.uv.fs_stat(d .. '/' .. n) then lic = d .. '/' .. n end
    end
  end
  assert(lic, 'no licence file found for ' .. lang)
  local text = table.concat(vim.fn.readfile(lic), '\n')
  assert(text:find('MIT License', 1, true) or text:find('Permission is hereby granted', 1, true),
    lang .. ': licence is not MIT, check manually: ' .. lic)
  vim.fn.writefile(vim.fn.readfile(lic), dst .. '/LICENSE')

  copy_queries(lang)
  table.insert(manifest, { lang = lang, url = info.url, rev = info.revision, loc = info.location })
  print(('vendored %-16s %s'):format(lang, info.revision:sub(1, 10)))
end

for _, lang in ipairs(QUERY_ONLY) do copy_queries(lang) end

-- THIRD_PARTY.md
local out = {
  '# Third-party code',
  '',
  'Generated by `scripts/vendor_ts.lua`. Do not edit by hand.',
  '',
  '## Tree-sitter grammars (`ts/grammars/`) — MIT',
  '',
  'Copyright belongs to the respective authors; each grammar directory contains its `LICENSE`.',
  '',
  '| Language | Source | Revision |',
  '|---|---|---|',
}
for _, m in ipairs(manifest) do
  table.insert(out, ('| %s | %s%s | `%s` |'):format(m.lang, m.url, m.loc and (' (`' .. m.loc .. '`)') or '', m.rev))
end
vim.list_extend(out, {
  '',
  '## Queries (`queries/`) — Apache-2.0',
  '',
  'Copied unmodified from <https://github.com/nvim-treesitter/nvim-treesitter>, revision `'
    .. vim.trim(run({ 'git', 'rev-parse', 'HEAD' }, nts)) .. '`.',
  'Licence text: `queries/LICENSE`. Includes the helper query sets `ecma`, `jsx`, `html_tags`.',
  '',
})
vim.fn.writefile(out, root .. '/THIRD_PARTY.md')
vim.fn.writefile(vim.fn.readfile(nts .. '/LICENSE'), root .. '/queries/LICENSE')
vim.fn.delete(tmp, 'rf')
print('done')
